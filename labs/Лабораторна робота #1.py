#беремо підставні числа
a=3
b=7

#1.Арифметика (+,-,*,/,%,**,//)
print(a + b)  #додати
print(a - b)  #відняти
print(a * b)  #помножити
print(a / b)  #поділити
print(a // b) #цілочисельне ділення
print(a % b)  #остача від ділення
print(a ** b) #піднесення

#2.Порівняння (>,<,>=,<=,==,!=)
print(a > b)  #більше
print(a < b)  #менше
print(a >= b) #більше або дорівнює
print(a <= b) #менше або дорівнює
print(a == b) #дорівнює
print(a != b) #не дорівнює








